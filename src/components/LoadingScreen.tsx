// Экран загрузки - показывается в самом начале, пока приложение проверяет,
// вошли ли вы в аккаунт (см. overallLoading/showLoadingScreen в App.tsx) -
// одинаково и для тех, кто уже входил раньше, и для тех, кто открывает сайт
// впервые. Ролик зациклен (loop) на случай, если проверка займёт дольше своих
// исходных 8 секунд.
//
// poster - статичная картинка (первый кадр видео, см. loading-screen-poster.jpg) -
// видна СРАЗУ, ещё до того как само видео (тяжелее картинки) успеет скачаться
// из интернета. Без неё на медленном мобильном соединении был бы шанс увидеть
// просто пустой белый экран вместо анимации, пока видео в пути - так на этом
// месте гарантированно есть хоть что-то похожее на первый кадр ролика.
//
// preload="auto" - явная просьба браузеру начать грузить видео заранее, а не
// ждать, пока оно реально понадобится (см. main.tsx - там ещё раньше есть
// отдельная подсказка <link rel="preload">, эта - подстраховка на случай,
// если тот приём почему-то не сработает в конкретном браузере/окружении).
//
// autoPlay + muted + playsInline - стандартное для браузеров сочетание:
// видео без звука браузер разрешает запускать само, без нажатия пользователем
// (обычное <video autoPlay> со звуком телефон/браузер тихо заблокировал бы).
// playsInline - чтобы видео на iPhone проигрывалось прямо на месте, а не
// разворачивалось на весь экран поверх интерфейса, как обычно происходит с
// видео на телефоне.
//
// Отдельный ручной вызов .play() в useEffect - подстраховка сверх атрибута
// autoPlay: в некоторых обёртках приложения (например, установленное как
// APK через Android TWA - см. android/, а не обычная вкладка Chrome) сам
// атрибут autoPlay иногда срабатывает ненадёжно, а явный вызов из кода -
// куда более стабильный, проверенный способ. .catch(() => {}) - если даже
// это не сработает, тогда виден хотя бы статичный кадр (poster) вместо
// сломанного вида, а не необработанная ошибка в консоли.
import { useEffect, useRef } from 'react'
import loadingVideo from '../assets/loading-screen.mp4'
import loadingPoster from '../assets/loading-screen-poster.jpg'

export function LoadingScreen() {
  const videoRef = useRef<HTMLVideoElement>(null)

  useEffect(() => {
    videoRef.current?.play().catch(() => {})
  }, [])

  return (
    <div className="h-full w-full overflow-hidden bg-white">
      <video
        ref={videoRef}
        src={loadingVideo}
        poster={loadingPoster}
        preload="auto"
        autoPlay
        muted
        loop
        playsInline
        className="h-full w-full object-cover"
      />
    </div>
  )
}
