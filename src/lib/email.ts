// Быстрая проверка формата адреса до отправки запроса.
// Полную проверку всё равно выполняет Supabase, потому что только почтовый
// сервис знает, существует ли адрес и можно ли доставить письмо.
export function isLikelyEmail(value: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value.trim())
}
