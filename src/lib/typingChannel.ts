// Общее для useTypingChannel.ts (один открытый разговор: слушает "печатает ли
// мне собеседник" И умеет сообщать "печатаю я сам") и useTypingStatus.ts (список
// в "Сообщениях": то же самое слушание, но сразу за несколькими людьми).
//
// Имя канала должно совпадать байт в байт у того, кто слушает, и у того, кто
// отправляет - иначе сообщения о "печатает" просто не дойдут, без единой ошибки
// (Supabase Realtime молча ничего не делает, если каналы называются по-разному).
// Поэтому вынесено в один файл, а не повторено в каждом хуке отдельно.

export const TYPING_CLEAR_MS = 3000

export function typingChannelName(userIdA: string, userIdB: string): string {
  return `typing:${[userIdA, userIdB].sort().join(':')}`
}
