// Тип анкеты. Раньше здесь же лежал массив тестовых (выдуманных) анкет для ленты -
// теперь лента показывает настоящих людей (см. src/lib/useFeedProfiles.ts), поэтому
// тестовых данных в этом файле больше нет.

import type { HobbyId } from './hobbies'

// Категория анкеты — по ней работают фильтры-таблетки над лентой.
// 'all' сюда не входит: "Все" — это не категория анкеты, а режим "показать всё".
export type ProfileCategory =
  | 'communication' // Общение
  | 'romance' // Романтика
  | 'hobbies' // Увлечения
  | 'fellow-travelers' // Попутчики
  | 'networking' // Нетворкинг
  | 'friendship' // Дружба

// Описываем форму одной анкеты. gender/age/height/languages необязательные - в базе
// (src/lib/useFeedProfiles.ts) эти поля тоже необязательные, человек мог их не заполнить.
export interface Profile {
  id: string // person's user_id - стабильный идентификатор, используется как React key
  gender?: 'male' | 'female' // пол анкеты — влияет на цвет карточки и букву на значке
  category: ProfileCategory // к какому фильтру относится анкета
  hobby?: HobbyId // конкретное хобби — заполнено только когда category === 'hobbies'
  isNew?: boolean // анкета появилась недавно (значок "New"), поле необязательное
  quote: string // короткая фраза от человека — то, что видно в карточке
  age?: number // возраст числом, чтобы можно было выделить его жирным
  height?: number // рост в сантиметрах
  languages?: string // на каких языках говорит человек, через запятую
  likedByMe: boolean // лайкнул ли уже я этого человека - нужно кнопке лайка, чтобы не спрашивать дважды
}
