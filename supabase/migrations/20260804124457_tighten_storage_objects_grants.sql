-- storage.objects - системная таблица самого сервиса Supabase Storage (общая
-- для ВСЕХ бакетов проекта, не только avatars, и не создаётся миграциями
-- этого проекта) - у anon/authenticated на ней по умолчанию есть ВСЕ права,
-- включая TRUNCATE/REFERENCES/TRIGGER, которые само Storage API никогда не
-- использует (тот же класс проблемы, что уже был со своими таблицами - см.
-- LESSONS.md: TRUNCATE игнорирует RLS полностью).
--
-- ПРОВЕРЕНО НА ДЕЛЕ (2026-08-04): эта команда ничего не меняет. Права ровно
-- те же самые до и после - ни через миграцию, ни выполненная вручную от роли
-- postgres. Своя таблица в той же базе (public.hidden_profiles) такой же
-- revoke спокойно принимает - значит дело не в правах роли postgres вообще,
-- а именно в том, что storage.objects принадлежит supabase_storage_admin, и
-- Supabase, похоже, сам следит за этими правами и восстанавливает их (скорее
-- всего для надёжности своего же Storage-сервиса при апдейтах на их стороне).
-- Оставлено в истории миграций как есть (уже применено, не переписываем
-- задним числом) - реальной дыры это не создаёт: TRUNCATE недостижим через
-- обычный REST-запрос/supabase-js (PostgREST не умеет его отправлять), а
-- INSERT/UPDATE/DELETE у anon всё равно отсекаются RLS-политиками бакета
-- (см. create_avatars_storage_bucket.sql - политики только "to authenticated").
revoke truncate, references, trigger on storage.objects from anon, authenticated;
