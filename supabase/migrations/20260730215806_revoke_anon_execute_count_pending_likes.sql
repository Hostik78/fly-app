-- Проверка советчика Supabase (db advisors) и прямой запрос к базе показали:
-- count_pending_likes() выполнима и от анонимного пользователя (anon), хотя
-- прошлая миграция явно написала "revoke all ... from public". Причина - у
-- Supabase есть свои права по умолчанию на новые функции в схеме public,
-- выданные ролям anon/authenticated напрямую (не через псевдо-роль public,
-- поэтому revoke ... from public их не затрагивает) - тот же класс проблемы,
-- что уже был с таблицами (см. LESSONS.md, история про TRUNCATE).
--
-- Функция и так просто вернёт 0 для anon (auth.uid() будет пустым), утечки
-- данных тут нет - но раз функция задумана только для вошедших пользователей,
-- явно запрещаем её анонимусам, а не полагаемся на то, что результат случайно
-- безобиден.
revoke execute on function public.count_pending_likes() from anon;
