-- Продолжение предыдущей миграции (revoke_execute_notify_push_webhook.sql):
-- советчик всё равно показывал предупреждение и после неё. Причина оказалась
-- другой, чем в прошлых похожих случаях (LESSONS.md) - на этот раз право было
-- у самой роли public (её Postgres выдаёт новым функциям по умолчанию сам,
-- без участия Supabase) - "revoke ... from anon, authenticated" её не трогает,
-- нужно отзывать явно у public тоже. Итог: у функций, которые не должны
-- вызываться напрямую никем, надо отзывать И у public (обычное поведение
-- Postgres), И явно у anon/authenticated (особенность Supabase) - проверено
-- обе причины бывают по отдельности, полагаться на то, что закрыл только
-- одну сторону, нельзя.
revoke execute on function public.notify_push_webhook() from public;
