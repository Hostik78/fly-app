-- Чтобы переписка обновлялась сама, без перезахода на экран, когда собеседник
-- прислал сообщение, нужна не только политика RLS (она уже есть - messages_select_own),
-- но и отдельное включение таблицы в публикацию supabase_realtime - без этого шага
-- Supabase Realtime вообще не присылает события о новых строках, молча ничего не
-- делая, без единой ошибки. RLS всё равно продолжает действовать: если бы кто-то
-- подписался на чужую переписку, событий по ней всё равно бы не пришло.
alter publication supabase_realtime add table public.messages;
